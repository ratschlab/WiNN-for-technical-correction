#!/usr/bin/env Rscript
# Splice a WiNN-only re-run into a previous frozen release.
#
# Competitor rows (ComBat, QC-RLSC, QC-RFSC, TIGER, SERRF and their variants) and
# the uncorrected Raw rows are copied unchanged from the previous release, because
# neither depends on WiNN; Raw is re-run only as a reproduction check
# (raw_max_abs_diff, runtimes excluded). All WiNN rows (three modes and ablation
# variants) come from the new aggregate. Tables without a method_id column are WiNN-only only
# when listed in winn_only_pattern; any other such table must be identical between
# releases. Competitor rows that the WiNN-only aggregate rebuilt from configuration
# (selection manifests, candidate scores, reuse audit) must equal the previous rows.
# --overlay names a newer partial release (e.g. the corrected-RFSC tables) whose
# tables supersede those under --old before splicing.
#
# Usage:
#   Rscript analysis/splice_winn_rerun.R --new=<new results/final> \
#     --old=<previous results/final> [--overlay=<newer partial results/final>] \
#     --out=<spliced results/final>
suppressPackageStartupMessages(library(dplyr))
args <- commandArgs(TRUE)
arg <- function(name, optional = FALSE) {
  hit <- sub(paste0("^--", name, "="), "", grep(paste0("^--", name, "="), args, value = TRUE))
  if (!length(hit) && optional) return(NULL)
  if (length(hit) != 1L) stop("Supply --", name, "=", call. = FALSE)
  hit
}
new_root <- normalizePath(arg("new"), mustWork = TRUE)
old_root <- normalizePath(arg("old"), mustWork = TRUE)
overlay_root <- arg("overlay", optional = TRUE)
if (!is.null(overlay_root)) overlay_root <- normalizePath(overlay_root, mustWork = TRUE)
out_root <- arg("out")
rerun <- strsplit(Sys.getenv("WINN_RERUN_METHODS",
                             "raw,winn_auto_qc,winn_auto_batch_qc,winn_fixed_no_qc"), ",")[[1]]
competitors <- c("combat", "qc_rlsc", "qc_rfsc", "tiger", "serrf")
is_competitor <- function(id) grepl(paste0("^(", paste(competitors, collapse = "|"), ")(_|$)"), id)
winn_only_pattern <- "^tables/(ablation_|partial_confounding_|selective_vs_forced_|simulation_seed_ablation_)"
# Competitor run evidence (run manifests, checksums) is not regenerated by a
# WiNN-only run, so these competitor rows are blank in the new aggregate.
competitor_evidence_not_rerun <- c("tables/competitor_reuse_audit.csv")
# Competitor rows rebuilt from the current analysis/config selection manifest; they
# carry the corrected QC-RFSC entries and must equal the overlay's manifest rows.
competitor_rows_from_config <- c(
  "tables/configuration_selection_manifest.csv" = "tables/endpoint_free_selection_manifest.csv"
)
id_columns <- c("analysis_family", "dataset_key", "seed_id", "split_id", "scenario_id",
                "confounding_type", "level", "method_id", "metric", "variant_id", "stage",
                "table_id", "candidate_id", "feature_id", "feature", "batch")

read_any <- function(path) {
  if (!file.exists(path) || file.size(path) <= 4L) return(NULL)
  d <- tryCatch(read.csv(path, stringsAsFactors = FALSE, check.names = FALSE,
                         colClasses = "character", na.strings = character()),
                error = function(e) NULL)
  if (is.null(d) || !ncol(d) || identical(names(d), "")) NULL else d
}
rel_files <- function(root) {
  if (is.null(root)) return(character())
  f <- list.files(file.path(root, "tables"), pattern = "[.]csv$", recursive = TRUE)
  file.path("tables", f)
}
new_files <- rel_files(new_root)
old_files <- union(rel_files(old_root), rel_files(overlay_root))
old_path <- function(rel) {
  if (!is.null(overlay_root) && file.exists(file.path(overlay_root, rel))) file.path(overlay_root, rel)
  else file.path(old_root, rel)
}
same_rows <- function(a, b) {
  if (is.null(a) || is.null(b) || !identical(sort(names(a)), sort(names(b)))) return(FALSE)
  b <- b[, names(a), drop = FALSE]
  ka <- do.call(paste, c(a, sep = "\r")); kb <- do.call(paste, c(b, sep = "\r"))
  identical(sort(ka), sort(kb))
}
log <- list()
note <- function(file, action, old_rows = NA_integer_, new_rows = NA_integer_, replaced = NA_integer_,
                 appended = NA_integer_, raw_max_abs_diff = NA_real_, source = "") {
  log[[length(log) + 1L]] <<- data.frame(file = file, action = action, old_rows = old_rows,
    new_rows = new_rows, replaced = replaced, appended = appended,
    raw_max_abs_diff = raw_max_abs_diff, old_source = source, stringsAsFactors = FALSE)
}
dir.create(file.path(out_root, "tables"), recursive = TRUE, showWarnings = FALSE)

for (rel in union(old_files, new_files)) {
  dest <- file.path(out_root, rel)
  dir.create(dirname(dest), recursive = TRUE, showWarnings = FALSE)
  src <- old_path(rel)
  src_label <- if (!is.null(overlay_root) && startsWith(src, overlay_root)) "overlay" else "old"
  old <- if (rel %in% old_files) read_any(src) else NULL
  new <- if (rel %in% new_files) read_any(file.path(new_root, rel)) else NULL
  n_old <- if (is.null(old)) 0L else nrow(old)
  n_new <- if (is.null(new)) 0L else nrow(new)

  # No usable new table: keep the previous one, which must hold no WiNN rows.
  if (is.null(new)) {
    if (is.null(old)) { note(rel, "skipped_empty_in_both", source = src_label); next }
    if (grepl(winn_only_pattern, rel)) {
      note(rel, "dropped_previous (WiNN-only; regenerated downstream)", n_old, n_new, source = src_label)
      next
    }
    if ("method_id" %in% names(old) && any(!is_competitor(old$method_id) & old$method_id != "raw")) {
      note(rel, "ERROR_previous_table_has_winn_rows_but_no_new_table", n_old, n_new, source = src_label)
      next
    }
    file.copy(src, dest, overwrite = TRUE)
    note(rel, "kept_previous (competitor-only or empty in WiNN-only aggregate)", n_old, n_new,
         source = src_label)
    next
  }
  if (is.null(old)) {
    file.copy(file.path(new_root, rel), dest, overwrite = TRUE)
    note(rel, "new_table", n_old, n_new, n_new, 0L, source = src_label)
    next
  }
  if (!"method_id" %in% names(new)) {
    if (grepl(winn_only_pattern, rel)) {
      file.copy(file.path(new_root, rel), dest, overwrite = TRUE)
      note(rel, "replaced_entirely (WiNN-only table)", n_old, n_new, n_new, 0L, source = src_label)
    } else if (same_rows(old, new)) {
      file.copy(src, dest, overwrite = TRUE)
      note(rel, "kept_previous (identical; no method_id)", n_old, n_new, source = src_label)
    } else {
      note(rel, "ERROR_non_winn_table_without_method_id_differs", n_old, n_new, source = src_label)
    }
    next
  }
  if (!identical(sort(names(old)), sort(names(new)))) {
    stop(rel, ": column sets differ between releases: ",
         paste(setdiff(union(names(old), names(new)), intersect(names(old), names(new))), collapse = ", "))
  }
  new <- new[, names(old), drop = FALSE]
  keys <- intersect(id_columns, names(old))
  key_of <- function(d) do.call(paste, c(lapply(keys, function(k) d[[k]]), sep = "\r"))
  # Competitor rows rebuilt from configuration in the WiNN-only aggregate must match.
  new_comp <- new[is_competitor(new$method_id), , drop = FALSE]
  old_comp <- old[is_competitor(old$method_id), , drop = FALSE]
  comp_check <- if (nrow(new_comp)) {
    if (same_rows(old_comp, new_comp)) "competitor_rows_identical" else "competitor_rows_differ"
  } else ""
  if (comp_check == "competitor_rows_differ" && rel %in% competitor_evidence_not_rerun) {
    comp_check <- "competitor_rows_kept_previous (run evidence not re-run)"
  }
  if (rel %in% names(competitor_rows_from_config) && is.null(overlay_root)) {
    # Historical (July-format) base: keep its competitor rows; the downstream
    # supplement integration applies the corrected QC-RFSC entries itself.
    comp_check <- "competitor_rows_kept_previous (historical base; no overlay)"
  } else if (rel %in% names(competitor_rows_from_config)) {
    ref <- read_any(old_path(competitor_rows_from_config[[rel]]))
    ref_comp <- if (is.null(ref)) NULL else ref[is_competitor(ref$method_id), , drop = FALSE]
    if (!is.null(ref_comp) && same_rows(ref_comp, new_comp)) {
      old_comp <- new_comp
      comp_check <- paste0("competitor_rows_from_current_config (equal to ",
                           basename(competitor_rows_from_config[[rel]]), ")")
    } else comp_check <- "competitor_rows_differ"
  }
  # Reproduction check on the uncorrected Raw reference (no WiNN involvement):
  # matched by identifier columns; numeric columns other than runtimes compared.
  raw_diff <- NA_real_
  old_raw <- old[old$method_id == "raw", , drop = FALSE]
  new_raw <- new[new$method_id == "raw", , drop = FALSE]
  if ("metric" %in% names(old)) {
    old_raw <- old_raw[!grepl("runtime", old_raw$metric), , drop = FALSE]
    new_raw <- new_raw[!grepl("runtime", new_raw$metric), , drop = FALSE]
  }
  if (nrow(old_raw) && nrow(new_raw)) {
    m <- match(key_of(old_raw), key_of(new_raw))
    num_cols <- setdiff(names(old)[vapply(names(old), function(col) {
      v <- old_raw[[col]][old_raw[[col]] != ""]
      length(v) > 0L && !anyNA(suppressWarnings(as.numeric(v)))
    }, logical(1))], c(keys, "runtime_sec", "execution_runtime_sec", "reported_method_runtime_sec",
                       "wall_sec", "seed", "task_id"))
    if (length(num_cols) && any(!is.na(m))) {
      a <- suppressWarnings(as.numeric(as.matrix(old_raw[!is.na(m), num_cols, drop = FALSE])))
      b <- suppressWarnings(as.numeric(as.matrix(new_raw[m[!is.na(m)], num_cols, drop = FALSE])))
      ok <- is.finite(a) & is.finite(b)
      raw_diff <- if (any(ok)) max(abs(a[ok] - b[ok])) else NA_real_
    }
    if (any(is.na(m))) raw_diff <- Inf
  }
  # Group replacement: previous competitor and Raw rows + new WiNN rows, ordered
  # by the previous release's grouping order.
  kept <- rbind(old_comp, old[old$method_id == "raw", , drop = FALSE])
  added <- new[!is_competitor(new$method_id) & new$method_id != "raw", , drop = FALSE]
  out <- rbind(kept, added)
  group_cols <- intersect(c("analysis_family", "dataset_key", "seed_id", "split_id", "scenario_id", "method_id"), names(out))
  group_key <- function(d) do.call(paste, c(lapply(group_cols, function(k) d[[k]]), sep = "\r"))
  old_order <- unique(group_key(old))
  rank <- match(group_key(out), old_order)
  rank[is.na(rank)] <- length(old_order) + 1L
  out <- out[order(rank, seq_len(nrow(out))), , drop = FALSE]
  n_old_rerun <- sum(!is_competitor(old$method_id) & old$method_id != "raw")
  write.csv(out, dest, row.names = FALSE, na = "")
  action <- if (nrow(added) == n_old_rerun) "spliced" else "spliced (re-run row count changed)"
  if (comp_check == "competitor_rows_differ") action <- paste0("ERROR_", comp_check)
  else if (nzchar(comp_check)) action <- paste0(action, "; ", comp_check)
  note(rel, action, n_old, n_new, n_old_rerun, nrow(added), raw_diff, source = src_label)
}

log <- bind_rows(log)
dir.create(file.path(out_root, "validation"), recursive = TRUE, showWarnings = FALSE)
write.csv(log, file.path(out_root, "validation", "winn_rerun_splice_log.csv"), row.names = FALSE, na = "")
print(log, row.names = FALSE)
if (any(grepl("^ERROR", log$action))) stop("Splice refused: see winn_rerun_splice_log.csv", call. = FALSE)
cat("Spliced release written to", out_root, "\n")
