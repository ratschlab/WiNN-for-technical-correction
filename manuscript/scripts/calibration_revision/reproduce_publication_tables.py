#!/usr/bin/env python3
"""Replay the frozen table pipeline in an isolated copy and compare outputs.

The source checkout supplies plotting aggregates, supporting exports and static
table inputs; the archive supplies the explicitly versioned benchmark tables.
The proof compares every final TeX byte and parsed CSV row after the pipeline.
It does not claim that copied static tables were generated by this pipeline.
"""
import argparse
import csv
import re
import shutil
import subprocess
from pathlib import Path

p = argparse.ArgumentParser()
p.add_argument("--source", type=Path, required=True)
p.add_argument("--archive", type=Path, required=True)
p.add_argument("--work", type=Path, required=True)
p.add_argument("--proof", type=Path, required=True)
a = p.parse_args()
a.source = a.source.resolve()
a.archive = a.archive.resolve()
a.work = a.work.resolve()
if a.work == a.source or a.source in a.work.parents:
    raise SystemExit("The isolated replay directory must be outside the source checkout")
if a.work.exists():
    raise SystemExit(f"Refusing to overwrite existing replay directory: {a.work}")
a.work.mkdir(parents=True)
for name in ("scripts", "generated/review_validation", "generated/revision_panel_inputs",
             "generated/supplementary_table_data", "generated/supplementary_tables",
             "figures/source_data"):
    shutil.copytree(a.source / name, a.work / name)
for name in ("figures/main_panels", "figures/supplementary_panels"):
    dst = a.work / name
    dst.mkdir(parents=True)
    for path in (a.source / name).glob("*.pdf"):
        shutil.copy2(path, dst / path.name)
tex_files = sorted((a.source / "generated/supplementary_tables").glob("*.tex"))
csv_files = sorted((a.source / "generated/supplementary_table_data").glob("*.csv"))
def numbered(paths, numbers):
    return [path.relative_to(a.source) for path in paths
            if (match := re.match(r"table_s(\d+)_", path.name)) and int(match[1]) in numbers]

core_outputs = numbered(tex_files + csv_files, set(range(4, 21)) | {26})
core_outputs = [path for path in core_outputs if path.name != "table_s12_lobo_fold_level.csv"]
core_outputs += [Path("generated/supplementary_table_data") / name for name in
                 ("supplementary_table_manifest.csv",)]
commands = [
    (["Rscript", "scripts/generate_supplementary_tables.R", f"--final-root={a.archive}"], core_outputs),
    (["Rscript", "scripts/nearest_baseline/generate_validation_tables.R"], numbered(tex_files, {23, 27, 28})),
    (["python3", "scripts/generate_review2_support_tables.py"], numbered(tex_files, {29, 30, 31})),
    (["Rscript", "scripts/generate_s24_paired_effects_table.R"], numbered(tex_files, {24})),
    (["python3", "scripts/condense_supplementary_tables.py"],
     [path.relative_to(a.source) for path in tex_files if path.name.startswith("condensed_")]),
]
regenerated = set()
with (a.work / "table_reproduction.log").open("w") as log:
    for command, outputs in commands:
        # Remove each producer's outputs immediately before it runs. Some early
        # integration steps read later tables as caption templates, so deleting
        # everything up front would incorrectly remove those required inputs.
        if not outputs:
            raise SystemExit(f"No declared outputs for {command}")
        for relative in outputs:
            (a.work / relative).unlink(missing_ok=True)
        print(" ".join(command), file=log, flush=True)
        subprocess.run(command, cwd=a.work, stdout=log, stderr=subprocess.STDOUT, check=True)
        missing = [str(relative) for relative in outputs if not (a.work / relative).is_file()]
        if missing:
            raise SystemExit("Generator did not recreate: " + ", ".join(missing))
        regenerated.update(outputs)
checks = []
for path in sorted((a.source / "generated/supplementary_tables").glob("*.tex")):
    relative = path.relative_to(a.source)
    checks.append(dict(file=str(relative), passed=path.read_bytes() == (a.work / relative).read_bytes(),
                       scope=("regenerated exact TeX bytes" if relative in regenerated else
                              "preserved static/template TeX input after pipeline")))
for path in sorted((a.source / "generated/supplementary_table_data").glob("*.csv")):
    relative = path.relative_to(a.source)
    with path.open(newline="") as original, (a.work / relative).open(newline="") as replay:
        passed = list(csv.DictReader(original)) == list(csv.DictReader(replay))
    checks.append(dict(file=str(relative), passed=passed,
                       scope=("regenerated parsed CSV rows" if relative in regenerated else
                              "preserved staged CSV input after pipeline")))
a.proof.parent.mkdir(parents=True, exist_ok=True)
with a.proof.open("w", newline="") as out:
    writer = csv.DictWriter(out, fieldnames=["file", "passed", "scope"])
    writer.writeheader()
    writer.writerows(checks)
failed = [r["file"] for r in checks if not r["passed"]]
print(f"{len(checks) - len(failed)}/{len(checks)} table reproduction checks passed; proof: {a.proof}")
if failed:
    raise SystemExit("Mismatch: " + ", ".join(failed))
